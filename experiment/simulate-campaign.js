// Power analysis for the field experiment: generates synthetic campaigns from the model with
// realistic measurement noise, analyses each with analyze.js, and reports how many repeats are
// needed to pin down the dip. Also writes one example campaign, clearly marked as synthetic.
// Usage: node experiment/simulate-campaign.js
'use strict';
const fs = require('fs');
const path = require('path');
const M = require('../src/rain-model.js');
const REF = require('../src/refined.js');
const A = require('./analyze.js');

const SETUP = {
  windAlong: 2.0,          // mean tailwind along the course (m/s)
  gustSD: 0.35,            // trial-to-trial spread of the mean wind (m/s)
  rainRate: 5,             // mean rain rate (mm/h)
  rainSD: 0.3,             // trial-to-trial log-normal spread of rain rate
  dropMm: 1.5,             // representative drop size
  courseM: 100,
  padCm2: 400,             // 20 × 20 cm pads
  scaleSD: 0.02,           // scale noise per weighing (g)
  handlingSD: 0.04,        // handling / drip loss per pad (fractional)
  speeds: [0.8, 1.2, 1.6, 2.0, 2.4, 2.8, 3.3, 4.0, 5.0],
};

function rng(seed) {
  let s = seed >>> 0;
  const u = () => { s = (s * 1664525 + 1013904223) >>> 0; return (s + 0.5) / 4294967296; };
  const n = () => Math.sqrt(-2 * Math.log(u())) * Math.cos(2 * Math.PI * u());
  return { u, n };
}

function synthTrial(id, v, r, S) {
  const U = S.windAlong + S.gustSD * r.n();
  const R = S.rainRate * Math.exp(S.rainSD * r.n() - S.rainSD * S.rainSD / 2);
  const rain = M.rainState({ rainRateMmH: R, dropDiamMm: S.dropMm });
  const T = S.courseM / v, Am2 = S.padCm2 / 1e4;
  const eta = REF.eta(S.dropMm, U - v, 0);
  const grams = (rate) => rate * Am2 * T * 1e6; // m³ → g
  const meas = (g) => Math.max(0, g * (1 + S.handlingSD * r.n()));
  const dry = () => 30 + 5 * r.u();
  const top = meas(grams(rain.C * rain.vt)), front = meas(grams(rain.C * eta * Math.max(0, v - U))), back = meas(grams(rain.C * eta * Math.max(0, U - v)));
  const td = dry(), fd = dry(), bd = dry();
  const w = (x) => +(x + S.scaleSD * r.n()).toFixed(2);
  return {
    trial_id: id, date: 'SYNTHETIC', time_start: '', course_m: S.courseM, speed_target_mps: v, duration_s: +T.toFixed(1),
    wind_along_mps: +(U + 0.2 * r.n()).toFixed(2), wind_across_mps: 0, rain_gauge_mm: +(R * T / 3600).toFixed(3),
    pad_area_cm2: S.padCm2, top_dry_g: w(td), top_wet_g: w(td + top), front_dry_g: w(fd), front_wet_g: w(fd + front),
    back_dry_g: w(bd), back_wet_g: w(bd + back), notes: 'synthetic',
  };
}

function campaign(repeats, seed, S = SETUP) {
  const r = rng(seed);
  const rows = [];
  let id = 1;
  for (let k = 0; k < repeats; k++) for (const v of S.speeds) rows.push(synthTrial(id++, v, r, S));
  return rows;
}

if (require.main === module) {
  const scenarios = [
    ['Typical', SETUP],
    ['Pessimistic (gusty, careless handling)', Object.assign({}, SETUP, { gustSD: 0.8, rainSD: 0.5, scaleSD: 0.05, handlingSD: 0.12 })],
  ];
  for (const [name, S] of scenarios) {
    console.log(`${name}: tailwind ${S.windAlong} m/s (±${S.gustSD} trial to trial), ${S.rainRate} mm/h (±${S.rainSD * 100}%), ${S.courseM} m course, ${S.padCm2} cm² pads, handling ±${S.handlingSD * 100}%`);
    console.log(`Speeds per repeat: ${S.speeds.join(', ')} m/s`);
    console.log('repeats  trials  median |Ux error|  95% CI width (median)  dip detected (ΔAIC > 10)');
    for (const reps of [1, 2, 3, 5]) {
      const errs = [], widths = [];
      let detected = 0;
      const N = 40;
      for (let i = 0; i < N; i++) {
        const res = A.analyse(campaign(reps, 100 + 31 * i + reps, S), { B: 120 });
        errs.push(Math.abs(res.wind.U - S.windAlong));
        widths.push(res.ci.U[1] - res.ci.U[0]);
        if (res.dAIC > 10) detected++;
      }
      const med = (a) => a.slice().sort((x, y) => x - y)[Math.floor(a.length / 2)];
      console.log(`${String(reps).padStart(7)}  ${String(reps * S.speeds.length).padStart(6)}  ${med(errs).toFixed(2).padStart(17)} m/s  ${med(widths).toFixed(2).padStart(18)} m/s  ${(100 * detected / N).toFixed(0).padStart(20)}%`);
    }
    console.log('');
  }
  const rows = campaign(2, 7);
  const cols = Object.keys(rows[0]);
  const out = '# SYNTHETIC DATA generated by experiment/simulate-campaign.js — not a measurement\n' +
    cols.join(',') + '\n' + rows.map(r => cols.map(c => r[c]).join(',')).join('\n') + '\n';
  fs.writeFileSync(path.join(__dirname, 'example_synthetic_trials.csv'), out);
  console.log('\nWrote experiment/example_synthetic_trials.csv (2 repeats). Analyse it with:');
  console.log('  node experiment/analyze.js experiment/example_synthetic_trials.csv');
}

module.exports = { campaign, SETUP };
