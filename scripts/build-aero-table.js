// Precomputes collection efficiencies on a grid so the browser and the analysis can interpolate
// instead of integrating trajectories. Usage: node scripts/build-aero-table.js > src/aero-table.js
const A = require('../src/aero.js');
const D = [0.1, 0.15, 0.2, 0.3, 0.4, 0.5, 0.7, 1, 1.5, 2, 3, 4, 5, 6];
const V = [0.25, 0.5, 0.75, 1, 1.5, 2, 3, 4, 5, 6, 8, 10];
const ANG = [0, 45, 90]; // airflow direction relative to the walking axis (torso is not round)
const TORSO = { a: 0.125, b: 0.225 }, LEG = { a: 0.065, b: 0.065 };
const torso = ANG.map(a => D.map(d => V.map(v => +A.collectionEfficiency(d, v * Math.cos(a * Math.PI / 180), v * Math.sin(a * Math.PI / 180), TORSO).toFixed(4))));
const leg = D.map(d => V.map(v => +A.collectionEfficiency(d, v, 0, LEG).toFixed(4)));
const table = { D, V, ANG, torso, leg, shapes: { torso: TORSO, leg: LEG } };
process.stdout.write(`// Generated by scripts/build-aero-table.js — do not edit by hand.
(function (root) {
  const table = ${JSON.stringify(table)};
  if (typeof module === 'object' && module.exports) module.exports = table;
  else root.RainAeroTable = table;
})(typeof self !== 'undefined' ? self : this);
`);
